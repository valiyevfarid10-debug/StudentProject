public class Student {
    public static void main(String[] args) {
        int age = 20;              // yaşı
        double height = 1.75;      // boyu (metr)
        double score = 85.5;       // imtahan balı
        boolean passed = true;     // keçib-keçmədiyi
        char firstLetter = 'A';    // adının ilk hərfi

        System.out.println("Yaşı: " + age);
        System.out.println("Boyu: " + height + " m");
        System.out.println("İmtahan balı: " + score);
        System.out.println("Keçib: " + passed);
        System.out.println("Adının ilk hərfi: " + firstLetter);
    }
}